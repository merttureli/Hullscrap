"""Rebuilds every sound effect of the game, byte-identically, from the recipes in sounds.py (numpy only, fixed seeds).
Run from anywhere:  python3 audio/_src/sfx/build_sfx.py   (about a minute)
Writes assets/audio/sfx/*.wav (44.1 kHz, 16-bit; mono one-shots, stereo loops), the ASSETS.md rows and audio/_src/sfx/report.txt
(peak, active RMS and the loop-seam check of every file). Options: --only name[,name] builds just those sounds (no report); --import-params only patches the .import files."""
import os
import re
import sys
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from dsp import *       # noqa: E402
from sounds import REG, FAMILY_RMS   # noqa: E402

ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
OUT = os.path.join(ROOT, "assets", "audio", "sfx")
SRC_NOTE = "original, generated by `audio/_src/sfx/build_sfx.py`"
LICENCE = "project-owned"
# sounds that mix in a committed sample (credited under "Sound samples" in ASSETS.md): sound name (and its _scrap/_neon lines) -> samples
SAMPLE_LAYERS = {"flak": "metal_clink", "missile_launch": "metal_clink", "ram_impact": "metal_bong", "collision": "metal_bong"}


def file_names():
    """Every output name in build order: a sound with variants is name_1, name_2, ..."""
    out = []
    for name, d in REG.items():
        out += [name] if d["variants"] == 1 else ["%s_%d" % (name, k + 1) for k in range(d["variants"])]
    return out


def render(name, d, k):
    x = np.asarray(d["fn"](k), dtype=float)
    if d["loop"]:
        length, tail = d["loop"]
        x = loop_fix(x, length, tail)     # no DC filter or fades: either would break the seam
    else:
        x = fade(trim(lp(dc_block(x), 7500, 0.7)))   # a last gentle low-pass: nothing harsh above ~8 kHz
    return finish(x, FAMILY_RMS[d["family"]])


def seam(x):
    """The loop-seam check, in numbers. step: the jump from the last sample to the first against the typical step of the signal (99th
    percentile of |diff|); a seamless loop has step <= 1. dip: the level of the 0.1 s window centred on the seam (the loop played twice)
    against the loop's mean level, in dB, next to the worst 0.1 s window found inside the file: the seam is no more of an outlier than
    the rest of the loop."""
    ch = [x] if x.ndim == 1 else [x[:, 0], x[:, 1]]
    m = n_of(0.1)
    steps, dips, worst = [], [], []
    for c in ch:
        d = np.abs(np.diff(c))
        steps.append(abs(c[0] - c[-1]) / (np.percentile(d, 99) + 1e-9))
        mean = np.sqrt(np.mean(c ** 2))
        two = np.concatenate([c, c])
        mid = len(c)
        dips.append(abs(20 * np.log10(np.sqrt(np.mean(two[mid - m // 2:mid + m // 2] ** 2)) / mean)))
        w = [np.sqrt(np.mean(two[i:i + m] ** 2)) for i in range(0, len(c), m // 2)]
        worst.append(max(abs(20 * np.log10(v / mean)) for v in w))
    return max(steps), max(dips), max(worst)


def main():
    only = None
    if "--import-params" in sys.argv:
        set_import_params()
        return
    if "--only" in sys.argv:
        only = set(sys.argv[sys.argv.index("--only") + 1].split(","))
    os.makedirs(OUT, exist_ok=True)
    lines = ["%-20s %5s %6s %8s %9s %s" % ("file", "chan", "secs", "peak dB", "rms dB", "loop seam (last-to-first step / typical step; level of the 0.1 s window at the seam vs the mean)")]
    total = 0
    for name, d in REG.items():
        for k in range(d["variants"]):
            fname = name if d["variants"] == 1 else "%s_%d" % (name, k + 1)
            if only and fname not in only and name not in only:
                continue
            x = render(name, d, k)
            path = os.path.join(OUT, fname + ".wav")
            write_wav(path, x)
            total += os.path.getsize(path)
            rms = 10 * np.log10(np.mean(x ** 2) + 1e-12) if d["loop"] else active_rms_db(x)
            s = ""
            if d["loop"]:
                st, dp, wo = seam(x)
                s = "step %.2f, dip %.2f dB (worst window inside %.2f dB)" % (st, dp, wo)
            lines.append("%-20s %5s %6.2f %8.2f %9.2f %s" % (fname + ".wav", "st" if x.ndim == 2 else "mono", len(x) / SR, peak_db(x), rms, s))
    if only:
        print("\n".join(lines))
        return
    lines.append("")
    lines.append("%d files, %.2f MB" % (len(lines) - 2, total / 1e6))
    open(os.path.join(HERE, "report.txt"), "w").write("\n".join(lines) + "\n")
    write_assets_rows()
    set_import_params()
    print("\n".join(lines))


def set_import_params():
    """Godot writes a .import next to every WAV the first time it imports the project; patch the ones that exist: loops loop (forward, to the
    end of the file) and every sample is kept as plain PCM (no lossy compression on a 0.1 s tick). Run again after the first import."""
    for name, d in REG.items():
        for fname in file_names_of(name, d):
            p = os.path.join(OUT, fname + ".wav.import")
            if not os.path.exists(p):
                continue
            s = open(p).read()
            s = re.sub(r"edit/loop_mode=\d", "edit/loop_mode=%d" % (2 if d["loop"] else 0), s)
            s = re.sub(r"compress/mode=\d", "compress/mode=0", s)
            open(p, "w").write(s)


def file_names_of(name, d):
    return [name] if d["variants"] == 1 else ["%s_%d" % (name, k + 1) for k in range(d["variants"])]


def write_assets_rows():
    """Replace the SFX rows of ASSETS.md. They go just before the `tests/` row (the sorted place), where the art rows end and the music
    rows (appended at the end) begin, so the three blocks do not collide when branches merge."""
    p = os.path.join(ROOT, "ASSETS.md")
    keep = [l for l in open(p).read().splitlines() if "assets/audio/sfx/" not in l]
    while keep and keep[-1] == "":
        keep.pop()
    def note(n):
        base = re.sub(r"(_scrap|_neon)?(_\d)?$", "", n)
        return SRC_NOTE + ("; layer: `audio/_src/sfx/samples/heavy/%s.wav`" % SAMPLE_LAYERS[base] if base in SAMPLE_LAYERS else "")
    rows = ["| `assets/audio/sfx/%s.wav` | %s | %s |" % (n, note(n), LICENCE) for n in sorted(file_names())]
    at = next((i for i, l in enumerate(keep) if l.startswith("| `tests/")), len(keep))
    open(p, "w").write("\n".join(keep[:at] + rows + keep[at:]) + "\n")


if __name__ == "__main__":
    main()
