def export(outdir=None):
    outdir = outdir or ART + '/tiles'
    os.makedirs(outdir, exist_ok=True)
    sh = Spr(64, 16)
    for k, a in enumerate((SCORCH, PLATE, CABLES, SCRAP)): sh.stamp(16 * k, 0, a)
    save(sh, outdir + '/wreck.png')
    J = {'frame': [16, 16], 'cells': [1, 1], 'anims': {'variants': [0, 4, 0]},
         'notes': 'Debris decal drawn over the floor in each cell of a wrecked component. 4 variants (frame index): 0 scorched floor, 1 twisted plate, 2 loose cables, 3 burnt scrap. '
                  'Generic, no family colour: pick a variant per cell by hash.'}
    with open(outdir + '/wreck.json', 'w') as f: json.dump(J, f, indent=1); f.write('\n')
    return sh
if __name__ == '__main__':
    export()
