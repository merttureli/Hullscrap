def poly_cells(pts):
    """scanline fill of a polygon (pixel centres)."""
    ys = [p[1] for p in pts]; cells = set()
    for y in range(int(min(ys)), int(max(ys)) + 1):
        xs = []
        for i in range(len(pts)):
            (x0, y0), (x1, y1) = pts[i], pts[(i + 1) % len(pts)]
            if y0 == y1: continue
            if min(y0, y1) <= y + 0.5 < max(y0, y1):
                xs.append(x0 + (x1 - x0) * ((y + 0.5) - y0) / (y1 - y0))
        xs.sort()
        for a, b in zip(xs[0::2], xs[1::2]):
            for x in range(int(round(a)), int(round(b))): cells.add((x, y))
    return cells

def depth_map(cells):
    d = {}; cur = set(cells); k = 0
    while cur:
        nxt = set()
        for (x, y) in cur:
            d[(x, y)] = k
        # peel: a cell is interior if all 4 neighbours are still in `cur`
        inner = {(x, y) for (x, y) in cur if all(q in cur for q in ((x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)))}
        cur = inner; k += 1
        if k > 8: break
    return d

def draw(w, h, polys, bands, sparks=(), smoke=()):
    """bands: chars for depth 0,1,2.. (last repeats). sparks: (x, y, ch)."""
    cells = set()
    for p in polys: cells |= poly_cells(p)
    s = Spr(w, h)
    d = depth_map(cells)
    for (x, y) in cells:
        k = min(d.get((x, y), 0), len(bands) - 1)
        s.put(x, y, bands[k])
    for (x, y, c) in smoke: s.put(x, y, c)
    for (x, y, c) in sparks: s.put(x, y, c)
    return s

