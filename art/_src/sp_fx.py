def spark():
    W, H = 13, 15
    def bolt(pts, extra=()):
        s = Spr(W, H)
        def line(a, b):
            n = max(abs(b[0] - a[0]), abs(b[1] - a[1]), 1)
            for i in range(n + 1):
                x = a[0] + round((b[0] - a[0]) * i / n); y = a[1] + round((b[1] - a[1]) * i / n)
                yield x, y
        allp = []
        for a, b in zip(pts, pts[1:]): allp += list(line(a, b))
        for (x, y) in allp:
            for dx in (-1, 1):
                if s.get(x + dx, y) == '.': s.put(x + dx, y, 'b')
        for (x, y) in allp: s.put(x, y, 'H')
        for (x, y, c) in extra: s.put(x, y, c)
        return s
    f = [bolt([(6, 14), (4, 11), (7, 8), (5, 5), (6, 0)], [(6, 13, 'H'), (3, 3, 'b'), (9, 6, 'c')]),
         bolt([(6, 14), (8, 10), (5, 7), (8, 4), (7, 0)]),
         bolt([(6, 14), (5, 10), (7, 6), (6, 3)], [(2, 8, 'b'), (10, 9, 'b'), (9, 3, 'c')])]
    return f, (6, 14)

