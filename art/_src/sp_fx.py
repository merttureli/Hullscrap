PAD = 5
def glow_frame(spr, rgb, r):
    g = Rgba(spr.w + 2 * PAD, spr.h + 2 * PAD)
    for y in range(spr.h):
        for x in range(spr.w):
            if spr.g[y][x] in 'yHc': glow(g, x + PAD + 0.5, y + PAD + 0.5, r * 0.7, rgb, 0.55, 1.8)
    return g
